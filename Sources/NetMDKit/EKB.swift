import Foundation

/// Enabling Key Block material for the secure-session handshake.
struct EKB {
    let rootKey: [UInt8]
    let id: UInt32
    let chain: [[UInt8]]
    let depth: Int
    let signature: [UInt8]

    /// The open-source EKB shared by every NetMD device.
    static let openSource = EKB(
        rootKey: [0x12, 0x34, 0x56, 0x78, 0x9a, 0xbc, 0xde, 0xf0, 0x0f, 0xed, 0xcb, 0xa9, 0x87, 0x65, 0x43, 0x21],
        id: 0x26422642,
        chain: [
            [0x25, 0x45, 0x06, 0x4d, 0xea, 0xca, 0x14, 0xf9, 0x96, 0xbd, 0xc8, 0xa4, 0x06, 0xc2, 0x2b, 0x81],
            [0xfb, 0x60, 0xbd, 0xdd, 0x0d, 0xbc, 0xab, 0x84, 0x8a, 0x00, 0x5e, 0x03, 0x19, 0x4d, 0x3e, 0xda],
        ],
        depth: 9,
        signature: [0x8f, 0x2b, 0xc3, 0x52, 0xe8, 0x6c, 0x5e, 0xd3, 0x06, 0xdc, 0xae, 0x18,
                    0xd2, 0xf3, 0x8c, 0x7f, 0x89, 0xb5, 0xe1, 0x85, 0x55, 0xa1, 0x05, 0xea]
    )

    /// Replacement EKB for MDS-JB980/JE780/NT1 decks whose leaf ID was wiped (all 0xFF).
    static let corruptedDeck = EKB(
        rootKey: Array("WMDPWMDPMiniDisc".utf8),
        id: 0x13371337,
        chain: [[0xb1, 0xd4, 0xaf, 0xfa, 0x80, 0xa0, 0xc9, 0x03, 0xc2, 0x58, 0x4b, 0x1b, 0x44, 0xaf, 0xc4, 0xa6]],
        depth: 9,
        signature: [0x6c, 0x2b, 0xc2, 0x8c, 0x45, 0x2b, 0x54, 0xf1, 0xc3, 0x59, 0x72, 0x3b,
                    0xe3, 0x19, 0x1f, 0x55, 0x17, 0x25, 0x64, 0x0e, 0x65, 0x8c, 0x81, 0x0b]
    )

    static func forDevice(leafID: [UInt8], vendorId: UInt16, productId: UInt16) -> EKB {
        if leafID.allSatisfy({ $0 == 0xff }) && vendorId == 0x054c && productId == 0x0081 { return .corruptedDeck }
        return .openSource
    }
}
